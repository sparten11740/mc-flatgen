# Pictures that are another's mirror image, left to right.
MIRRORED = {}


def masks():
    """Every picture's mask as rows of letters, its own and the mirrored ones."""
    found = {name: (style, [row for row in text.strip("\n").split("\n")]) for name, (style, text) in PICTURES.items()}
    for name, source in MIRRORED.items():
        style, rows = found[source]
        found[name] = (style, [row[::-1] for row in rows])
    return found


def letter(rows, x, y):
    """The material at a pixel; clear outside the picture."""
    if 0 <= y < len(rows) and 0 <= x < len(rows[y]):
        return rows[y][x]
    return "."


def material(own):
    """A letter's material, the same in either case."""
    return MATERIALS[own.upper()]


def shade(rows, x, y):
    """The shade of a material's pixel: its index into the material's shades."""
    own = letter(rows, x, y)
    edge = {(dx, dy): letter(rows, x + dx, y + dy) != own for dx, dy in ((0, -1), (-1, 0), (0, 1), (1, 0))}
    if edge[(0, -1)] or edge[(-1, 0)]:
        return 3
    if edge[(0, 1)] or edge[(1, 0)]:
        return 1
    return 2


def inside(rows):
    """Pixels of a picture: upper-case shapes outlined inside, lower-case ones outside."""
    pixels = {}
    for y, row in enumerate(rows):
        for x, own in enumerate(row):
            if own == "." or own.islower():
                continue
            outlined = any(letter(rows, x + dx, y + dy) == "." for dx, dy in ((0, -1), (-1, 0), (0, 1), (1, 0)))
            pixels[(x, y)] = material(own)[0 if outlined else shade(rows, x, y)]
    pixels.update(outside(["".join(own if own.islower() else "." for own in row) for row in rows]))
    return pixels


def outside(rows):
    """Pixels of shapes outlined outside: a badge, or a picture's thin shapes."""
    pixels = {}
    for y, row in enumerate(rows):
        for x, own in enumerate(row):
            if own != ".":
                pixels[(x, y)] = material(own)[shade(rows, x, y)]
    for y in range(16):
        for x in range(16):
            near = [letter(rows, x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1)]
            solid = [found for found in near if found != "."]
            if letter(rows, x, y) == "." and solid:
                pixels[(x, y)] = material(solid[0])[0]
    return pixels


def png(pixels):
    """A 16 by 16 RGBA PNG of these pixels, the others clear."""
    raw = b""
    for y in range(16):
        raw += b"\x00"
        for x in range(16):
            colour = pixels.get((x, y))
            raw += struct.pack(">I", (colour << 8) | 0xFF) if colour is not None else b"\x00\x00\x00\x00"

    def chunk(kind, data):
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", 16, 16, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def main():
    os.makedirs(OUT, exist_ok=True)
    for name, (style, rows) in sorted(masks().items()):
        if len(rows) != 16 or any(len(row) != 16 for row in rows):
            raise SystemExit(f"{name} is not 16 by 16")
        with open(os.path.join(OUT, name + ".png"), "wb") as file:
            file.write(png(inside(rows) if style == "inside" else outside(rows)))


if __name__ == "__main__":
    main()
